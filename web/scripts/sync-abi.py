#!/usr/bin/env python3
"""Copies contract ABIs and live addresses into the app, which deploys on its own."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
lib = root / "web/src/lib"
contracts = root / "contracts"

abis = {
    "managerAbi": "BinStepManager",
    "hookAbi": "BinStepHook",
    "swapRouterAbi": "PoolSwapTest",
}
out = ["// Generated by scripts/sync-abi.py. Do not edit.\n"]
for name, contract in abis.items():
    abi = json.loads((contracts / f"out/{contract}.sol/{contract}.json").read_text())["abi"]
    out.append(f"export const {name} = {json.dumps(abi)} as const;\n")
(lib / "abi.ts").write_text("\n".join(out))
(lib / "deployment.json").write_text((contracts / "deployments/base-sepolia.json").read_text())
